# frozen_string_literal: true

require "json"
require "tomlrb"
require_relative "shapes"

# What a differential outcome means against the accepted divergences and the
# candidate ledger. Kept apart from the runner so it is testable without workers.
module DiffLedger
  DEFAULT_MILESTONE = "M1"
  FAILED_RUNS = %w[crash timeout].freeze
  MATCHED = %w[same accepted].freeze
  DIVERGENCE_KEYS = %w[id expected actual].freeze

  module_function

  def load_divergences(path)
    return [] unless File.exist?(path)

    Tomlrb.load_file(path).fetch("divergences", [])
  end

  def divergence_problems(divergences, compat)
    divergences.flat_map do |divergence|
      id = divergence["id"].to_s
      structure = divergence["structure"]
      keys = structure ? %w[id] : DIVERGENCE_KEYS
      missing = keys.select { |key| divergence[key].to_s.empty? }
      problems = missing.empty? ? [] : ["divergence #{id.inspect}: needs #{missing.join(", ")}"]
      unknown = structure && !DiffShapes::STRUCTURES.key?(structure)
      problems << "divergence #{id}: unknown structure #{structure.inspect}" if unknown
      next problems if compat.dig(divergence["compat"], "status") == "deviation"

      problems + ["divergence #{id}: compat #{divergence["compat"].inspect} is not a compat.toml deviation"]
    end
  end

  def crashed?(outcomes)
    outcomes.any? { |outcome| FAILED_RUNS.include?(outcome.first) }
  end

  # Each differing step must be accepted on its own, so an accepted difference
  # in one step never covers a new one in another.
  def classify(expected, actual, divergences)
    return "same" if expected == actual
    return "crashed" if crashed?(actual)
    return "diverged" unless expected.size == actual.size

    accepted = expected.zip(actual).reject { |pair| pair[0] == pair[1] }.map do |step_expected, step_actual|
      divergences.find { |divergence| matches?(divergence, step_expected, step_actual) }
    end
    accepted.all? ? "accepted:#{accepted.map { |divergence| divergence["id"] }.uniq.sort.join(",")}" : "diverged"
  end

  def matches?(divergence, expected, actual)
    structure = divergence["structure"]
    return DiffShapes.match?(structure, expected, actual) if structure

    Regexp.new(divergence["expected"]).match?(JSON.generate(expected)) &&
      Regexp.new(divergence["actual"]).match?(JSON.generate(actual))
  end

  # What a shrunk variant must keep: the first differing step and how it differs,
  # with digits blurred so the same failure on a smaller value still matches.
  def signature(expected, actual)
    index = (0...[expected.size, actual.size].max).find { |i| expected[i] != actual[i] }
    step_expected = expected[index] || []
    step_actual = actual[index] || []
    message = step_actual.first == "raise" ? step_actual.dig(2, 3).to_s : ""
    [index, step_expected.first, step_actual.first, step_actual[1].to_s, message.gsub(/0x\h+|\d+/, "#")]
  end

  def ledger_status(previous, observed)
    case observed
    when "diverged" then previous.to_s.start_with?("xfail:", "crash:") ? previous : "xfail:#{DEFAULT_MILESTONE}"
    when "crashed" then previous.to_s.start_with?("crash:") ? previous : "crash:#{DEFAULT_MILESTONE}"
    else observed
    end
  end

  # An xfail case may diverge but not crash; a crash case may do either.
  ALLOWED = { "xfail" => %w[diverged], "crash" => %w[diverged crashed] }.freeze

  def ledger_problems(ledger, results, milestones)
    problems = results.filter_map { |result| case_problem(ledger.dig(result["id"], "status"), result, milestones) }
    problems + (ledger.keys - results.map { |result| result["id"] }).map { |id| "#{id}: in the ledger but did not run" }
  end

  def case_problem(status, result, milestones)
    id = result["id"]
    observed = result["class"]
    return "#{id}: not in the ledger (#{observed})" if status.nil?

    kind, milestone = status.split(":", 2)
    allowed = ALLOWED[kind]
    return ("#{id}: expected #{status}, got #{observed}" unless status == observed) unless allowed
    return "#{id}: undeclared milestone #{milestone}" unless milestones.include?(milestone)
    return if allowed.include?(observed)
    return "#{id}: ratchet: #{status} now #{observed}; update the ledger" if MATCHED.include?(observed.split(":").first)

    "#{id}: #{status} now #{observed}; a candidate crash needs crash:<milestone>"
  end

  def dump_ledger(statuses, command = "ruby test/diff/run.rb --write-ledger")
    lines = ["# Generated by `#{command}`; edit milestones by hand, not the layout.", ""]
    statuses.sort.each do |id, status|
      lines << "[cases.#{JSON.generate(id)}]"
      lines << "status = #{JSON.generate(status)}"
      lines << ""
    end
    lines.join("\n")
  end
end
