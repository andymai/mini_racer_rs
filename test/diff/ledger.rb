# frozen_string_literal: true

require "json"
require "tomlrb"

# What a differential outcome means against the accepted divergences and the
# candidate ledger. Kept apart from the runner so it is testable without workers.
module DiffLedger
  DEFAULT_MILESTONE = "S3"
  DIVERGENCE_KEYS = %w[id expected actual].freeze

  module_function

  def load_divergences(path)
    return [] unless File.exist?(path)

    Tomlrb.load_file(path).fetch("divergences", [])
  end

  def divergence_problems(divergences, compat)
    divergences.flat_map do |divergence|
      id = divergence["id"].to_s
      missing = DIVERGENCE_KEYS.select { |key| divergence[key].to_s.empty? }
      problems = missing.empty? ? [] : ["divergence #{id.inspect}: needs #{missing.join(", ")}"]
      next problems if compat.dig(divergence["compat"], "status") == "deviation"

      problems + ["divergence #{id}: compat #{divergence["compat"].inspect} is not a compat.toml deviation"]
    end
  end

  def classify(expected, actual, divergences)
    return "same" if expected == actual

    expected_json = JSON.generate(expected)
    actual_json = JSON.generate(actual)
    accepted = divergences.find do |divergence|
      Regexp.new(divergence["expected"]).match?(expected_json) && Regexp.new(divergence["actual"]).match?(actual_json)
    end
    accepted ? "accepted:#{accepted["id"]}" : "diverged"
  end

  def ledger_status(previous, observed)
    return observed unless observed == "diverged"

    previous.to_s.start_with?("xfail:") ? previous : "xfail:#{DEFAULT_MILESTONE}"
  end

  def ledger_problems(ledger, results, milestones)
    problems = results.filter_map do |result|
      status = ledger.dig(result["id"], "status")
      observed = result["class"]
      if status.nil? then "#{result["id"]}: not in the ledger (#{observed})"
      elsif status.start_with?("xfail:")
        milestone = status.delete_prefix("xfail:")
        next "#{result["id"]}: undeclared milestone #{milestone}" unless milestones.include?(milestone)

        "#{result["id"]}: ratchet: #{status} now #{observed}; update the ledger" unless observed == "diverged"
      elsif status != observed
        "#{result["id"]}: expected #{status}, got #{observed}"
      end
    end
    problems + (ledger.keys - results.map { |result| result["id"] }).map { |id| "#{id}: in the ledger but did not run" }
  end

  def dump_ledger(statuses)
    lines = ["# Generated by `ruby test/diff/run.rb --write-ledger`; edit milestones by hand, not the layout.", ""]
    statuses.sort.each do |id, status|
      lines << "[cases.#{JSON.generate(id)}]"
      lines << "status = #{JSON.generate(status)}"
      lines << ""
    end
    lines.join("\n")
  end
end
