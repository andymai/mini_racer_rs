# frozen_string_literal: true

require "json"
require "rbconfig"
require "tomlrb"

module UpstreamLedger
  ROOT = File.expand_path("../..", __dir__)
  UPSTREAM = File.join(ROOT, "vendor", "mini_racer")
  MILESTONES = File.join(__dir__, "milestones.toml")
  DEFAULT_TIMEOUT = 120

  PASSING = %w[pass].freeze
  FAILING = %w[fail error].freeze
  CRASHING = %w[crash timeout].freeze

  module_function

  def leg(engine: RUBY_ENGINE, version: RUBY_ENGINE_VERSION, os: RbConfig::CONFIG["host_os"], cpu: RbConfig::CONFIG["host_cpu"])
    minor = version[/\A\d+\.\d+/]
    os_name = os.include?("darwin") ? "macos" : "linux"
    arch = %w[aarch64 arm64].include?(cpu) ? "arm64" : cpu
    "#{engine}-#{minor}-#{os_name}-#{arch}"
  end

  def milestones
    Tomlrb.load_file(MILESTONES).fetch("milestones").keys
  end

  def load(path)
    File.exist?(path) ? Tomlrb.load_file(path).fetch("tests", {}) : {}
  end

  def effective(entry, leg_key)
    override = entry.dig("overrides", leg_key) || {}
    entry.except("overrides").merge(override)
  end

  def timeout_for(entry)
    entry&.fetch("timeout_s", nil) || DEFAULT_TIMEOUT
  end

  # One expectation check. Returns nil when the observed result is what the
  # ledger status promises, otherwise a short reason.
  def verdict(status, result)
    kind, = status.split(":", 2)
    case kind
    when "pass" then "regression: expected pass, got #{result}" unless PASSING.include?(result)
    when "upstream-skip" then "expected an upstream skip, got #{result}" unless result == "skip"
    when "upstream-fail", "deviation", "xfail"
      return "ratchet: #{status} now passes; update the ledger" if PASSING.include?(result)

      "expected a failure, got #{result}" unless (FAILING + CRASHING).include?(result)
    when "crash"
      "ratchet: #{status} now passes; update the ledger" if PASSING.include?(result)
    when "flaky" then nil
    else "unknown status #{status}"
    end
  end

  def malformed(id, entry, known_milestones)
    status = entry["status"].to_s
    kind, detail = status.split(":", 2)
    problems = []
    problems << "#{id}: missing status" if status.empty?
    problems << "#{id}: upstream-fail needs a cause" if kind == "upstream-fail" && entry["cause"].to_s.empty?
    problems << "#{id}: unknown status #{status}" unless %w[pass upstream-skip upstream-fail deviation xfail crash
                                                            flaky].include?(kind)
    if %w[xfail crash].include?(kind) && !known_milestones.include?(detail)
      problems << "#{id}: undeclared milestone #{detail.inspect}"
    end
    problems << "#{id}: #{kind} needs a target" if %w[deviation flaky].include?(kind) && detail.to_s.empty?
    problems
  end

  def toml_string(value)
    JSON.generate(value.to_s)
  end

  def dump(tests)
    lines = ["# Generated by `rake ledger:merge`; edit statuses and causes by hand, not the layout.", ""]
    tests.sort.each do |id, entry|
      lines << "[tests.#{toml_string(id)}]"
      entry.except("overrides").sort.each do |key, value|
        lines << "#{key} = #{value.is_a?(Integer) ? value : toml_string(value)}"
      end
      (entry["overrides"] || {}).sort.each do |leg_key, override|
        lines << ""
        lines << "[tests.#{toml_string(id)}.overrides.#{toml_string(leg_key)}]"
        override.sort.each { |key, value| lines << "#{key} = #{toml_string(value)}" }
      end
      lines << ""
    end
    lines.join("\n")
  end
end
