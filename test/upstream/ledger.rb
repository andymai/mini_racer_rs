# frozen_string_literal: true

require "json"
require "rbconfig"
require "tomlrb"

module UpstreamLedger
  ROOT = File.expand_path("../..", __dir__)
  UPSTREAM = File.join(ROOT, "vendor", "mini_racer")
  MILESTONES = File.join(__dir__, "milestones.toml")
  DEFAULT_TIMEOUT = 120
  SUITE_ID = "__suite__"

  PASSING = %w[pass].freeze
  FAILING = %w[fail error].freeze
  CRASHING = %w[crash timeout].freeze
  NOT_PASSING = (FAILING + CRASHING + %w[skip]).freeze
  KINDS = %w[pass upstream-skip upstream-fail deviation xfail crash flaky].freeze
  # Each non-passing status accepts exactly the results `rake ledger:merge`
  # records it for, so a test that starts crashing under xfail needs a ledger
  # update. A crash entry may see a plain failure: across seeds, one crash is
  # enough to record crash.
  ACCEPTS = {
    "upstream-skip" => %w[skip],
    "upstream-fail" => NOT_PASSING,
    "deviation" => NOT_PASSING,
    "xfail" => FAILING + %w[skip],
    "crash" => NOT_PASSING,
  }.freeze

  module_function

  def leg(engine: RUBY_ENGINE, version: RUBY_ENGINE_VERSION, os: RbConfig::CONFIG["host_os"], cpu: RbConfig::CONFIG["host_cpu"])
    minor = version[/\A\d+\.\d+/]
    os_name = os.include?("darwin") ? "macos" : "linux"
    arch = %w[aarch64 arm64].include?(cpu) ? "arm64" : cpu
    "#{engine}-#{minor}-#{os_name}-#{arch}"
  end

  def milestones
    Tomlrb.load_file(MILESTONES).fetch("milestones").keys
  end

  def load(path)
    File.exist?(path) ? Tomlrb.load_file(path).fetch("tests", {}) : {}
  end

  def known_legs(path)
    File.exist?(path) ? Tomlrb.load_file(path).fetch("legs", []) : []
  end

  def effective(entry, leg_key)
    return nil unless entry

    entry.except("overrides").merge(entry.dig("overrides", leg_key) || {})
  end

  def timeout_for(entry, leg_key)
    effective(entry, leg_key)&.fetch("timeout_s", nil) || DEFAULT_TIMEOUT
  end

  # One expectation check. Returns nil when the observed result is what the
  # ledger status promises, otherwise a short reason.
  def verdict(status, result)
    kind, = status.split(":", 2)
    case kind
    when "pass" then "regression: expected pass, got #{result}" unless PASSING.include?(result)
    when *ACCEPTS.keys
      return "ratchet: #{status} now passes; update the ledger" if PASSING.include?(result)

      "expected #{status}, got #{result}; update the ledger" unless ACCEPTS.fetch(kind).include?(result)
    when "flaky" then nil
    else "unknown status #{status}"
    end
  end

  def malformed_status(where, entry, known_milestones)
    status = entry["status"].to_s
    kind, detail = status.split(":", 2)
    return ["#{where}: missing status"] if status.empty?
    return ["#{where}: unknown status #{status}"] unless KINDS.include?(kind)

    problems = []
    problems << "#{where}: upstream-fail needs a cause" if kind == "upstream-fail" && entry["cause"].to_s.empty?
    if %w[xfail crash].include?(kind) && !known_milestones.include?(detail)
      problems << "#{where}: undeclared milestone #{detail.inspect}"
    end
    problems << "#{where}: #{kind} needs a target" if %w[deviation flaky].include?(kind) && detail.to_s.empty?
    problems
  end

  def malformed(id, entry, known_milestones)
    problems = malformed_status(id, entry, known_milestones)
    (entry["overrides"] || {}).each_key do |leg_key|
      problems += malformed_status("#{id} on #{leg_key}", effective(entry, leg_key), known_milestones)
    end
    problems
  end

  def toml_value(value)
    value.is_a?(Integer) ? value.to_s : JSON.generate(value.to_s)
  end

  def dump(tests, legs = [])
    lines = ["# Generated by `rake ledger:merge`; edit statuses and causes by hand, not the layout.", ""]
    unless legs.empty?
      quoted = legs.sort.map { |leg_key| JSON.generate(leg_key) }
      inline = "legs = [#{quoted.join(", ")}]"
      # The same layout taplo picks, so a regenerated ledger passes `taplo fmt --check`.
      lines.concat(inline.size <= 100 ? [inline] : ["legs = [", *quoted.map { |leg_key| "  #{leg_key}," }, "]"])
      lines << ""
    end
    tests.sort.each do |id, entry|
      lines << "[tests.#{JSON.generate(id)}]"
      entry.except("overrides").sort.each { |key, value| lines << "#{key} = #{toml_value(value)}" }
      (entry["overrides"] || {}).sort.each do |leg_key, override|
        lines << ""
        lines << "[tests.#{JSON.generate(id)}.overrides.#{JSON.generate(leg_key)}]"
        override.sort.each { |key, value| lines << "#{key} = #{toml_value(value)}" }
      end
      lines << ""
    end
    lines.join("\n")
  end
end
