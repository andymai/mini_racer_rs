# frozen_string_literal: true

require_relative "surface"

module CompatRender
  ROOT = CompatSurface::ROOT
  ENGINE_NAMES = { "ruby" => "CRuby", "truffleruby" => "TruffleRuby" }.freeze
  START = "<!-- compat-table:start -->"
  FINISH = "<!-- compat-table:end -->"
  GENERATED = "Generated by `rake compat:render` from compat.toml and compat/surface.json; do not edit."

  module_function

  def outputs(ledger, surface)
    entries = ledger.fetch("ids", {})
    readme = File.read(File.join(ROOT, "README.md"))
    {
      "COMPATIBILITY.md" => compatibility(entries, surface, ledger.fetch("extra", {})),
      "README.md" => readme_region(readme, entries, surface),
    }
  end

  # TruffleRuby runs upstream's backend, so every id it has is done there.
  def status_on(entries, id, engine)
    engine == "truffleruby" ? "done" : entries.dig(id, "status")
  end

  def label(status)
    status.to_s.start_with?("todo:") ? "planned (#{status.delete_prefix("todo:")})" : status.to_s
  end

  def table(ids)
    engines = CompatSurface::ENGINES.map { |engine| ENGINE_NAMES.fetch(engine) }
    rows = ids.group_by { |id| CompatSurface.split(id).first }.sort.map do |base, group|
      cells = CompatSurface::ENGINES.map do |engine|
        id = group.find { |candidate| CompatSurface.applies?(candidate, engine) }
        id ? yield(id, engine) : "n/a"
      end
      "| `#{base}` | #{cells.join(" | ")} |"
    end
    ["| Id | #{engines.join(" | ")} |", "|---|#{"---|" * engines.size}", *rows]
  end

  def additions(extra)
    return [] if extra.empty?

    ["## Additions", "", "What mini_racer_rs adds under `MiniRacerRs`. An internal id is not for callers.", "",
     *table(extra.keys) { |id, _| extra.dig(id, "status") }, "",]
  end

  def counts(entries, surface)
    CompatSurface::ENGINES.map do |engine|
      statuses = surface.fetch("ids").select { |id| CompatSurface.applies?(id, engine) }
                        .map { |id| status_on(entries, id, engine).to_s.sub(/\Atodo:.*/, "todo") }
      behaviors = entries.keys.count { |id| CompatSurface.kind(id) == "behavior" && CompatSurface.applies?(id, engine) }
      tally = statuses.tally
      "| #{ENGINE_NAMES.fetch(engine)} | #{tally.fetch("done", 0)} | #{tally.fetch("todo", 0)} | " \
        "#{tally.fetch("deviation", 0) + behaviors} |"
    end
  end

  def summary(entries, surface)
    ["| Engine | Done | Planned | Deviation |", "|---|---|---|---|", *counts(entries, surface)]
  end

  def deviations(entries)
    entries.select { |_, entry| entry["status"] == "deviation" }.sort.flat_map do |id, entry|
      review = entry["approved"] ? "Approved #{entry["approved"]}." : "Pending review."
      ["### `#{id}`", "", entry.fetch("reason").strip, "", review, ""]
    end
  end

  def compatibility(entries, surface, extra = {})
    lines = [
      "# Compatibility with mini_racer #{surface.fetch("mini_racer")}", "", "<!-- #{GENERATED} -->", "",
      *summary(entries, surface), "",
      "## Surface", "", *table(surface.fetch("ids")) { |id, engine| label(status_on(entries, id, engine)) }, "",
      *additions(extra),
    ]
    devs = deviations(entries)
    lines.push("## Deviations", "", *devs) unless devs.empty?
    "#{lines.join("\n").rstrip}\n"
  end

  def readme_region(readme, entries, surface)
    before, rest = readme.split(START, 2)
    raise ArgumentError, "README.md has no #{START} marker" unless rest

    _, after = rest.split(FINISH, 2)
    raise ArgumentError, "README.md has no #{FINISH} marker" unless after

    region = ["## Compatibility", "", *summary(entries, surface), "", "See [COMPATIBILITY.md](COMPATIBILITY.md)."]
    "#{before}#{START}\n#{region.join("\n")}\n#{FINISH}#{after}"
  end
end

if $PROGRAM_NAME == __FILE__
  outputs = CompatRender.outputs(CompatSurface.load_ledger, CompatSurface.load_surface)
  if ARGV.include?("--check")
    drifted = outputs.reject { |path, text| File.exist?(File.join(CompatRender::ROOT, path)) && File.read(File.join(CompatRender::ROOT, path)) == text }
    abort "out of date; run `rake compat:render`: #{drifted.keys.join(", ")}" unless drifted.empty?

    puts "compat outputs are current"
  else
    outputs.each { |path, text| File.write(File.join(CompatRender::ROOT, path), text) }
    puts "wrote #{outputs.keys.join(", ")}"
  end
end
